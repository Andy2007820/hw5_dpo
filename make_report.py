OUT = "2025310236_彭浩洋_实验作业五.docx"

doc = Document(SRC)
body = doc.element.body

# ---------- 1. 从模板抽出「原型」：每种样式一个段落、每个表格一份 XML ----------
proto_p = {}
for p in doc.paragraphs:
    proto_p.setdefault(p.style.name, copy.deepcopy(p._p))
proto_t = [copy.deepcopy(t._tbl) for t in doc.tables]
NAME_LINE = doc.paragraphs[1].text

sectPr = body.find(qn("w:sectPr"))
if sectPr is None:
    raise SystemExit("模板里找不到 sectPr")

# ---------- 2. 清空正文（保留节属性） ----------
for child in list(body):
    if child is not sectPr:
        body.remove(child)


def P(style, text, bold=False):
    """复用模板样式的段落"""
    el = copy.deepcopy(proto_p[style])
    sectPr.addprevious(el)
    par = Paragraph(el, doc)
    runs = par.runs
    if runs:
        runs[0].text = text
        for r in runs[1:]:
            r._element.getparent().remove(r._element)
    else:
        par.add_run(text)
    return par


def _fill(cell, text):
    par = cell.paragraphs[0]
    runs = par.runs
    if runs:
        runs[0].text = str(text)
        for r in runs[1:]:
            r._element.getparent().remove(r._element)
    else:
        par.add_run(str(text))
    for extra in cell.paragraphs[1:]:
        extra._element.getparent().remove(extra._element)


def T(proto_idx, rows):
    """复用模板某个表格的 XML 结构，按数据行数增删行"""
    el = copy.deepcopy(proto_t[proto_idx])
    sectPr.addprevious(el)
    tbl = Table(el, doc)
    while len(tbl.rows) > len(rows):
        el.remove(tbl.rows[-1]._tr)
    while len(tbl.rows) < len(rows):
        el.append(copy.deepcopy(tbl.rows[-1]._tr))
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            _fill(tbl.rows[i].cells[j], val)
    return tbl


